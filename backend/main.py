"""
CineMetrics FastAPI Application
================================
Main entry point for the CineMetrics analytics API.

This application serves processed MovieLens analytics data generated by
Hadoop MapReduce jobs. It loads all data into memory at startup for
fast response times, and exposes RESTful endpoints for the React dashboard.

Usage:
    cd backend
    uvicorn main:app --reload --port 8000
"""

import logging
from contextlib import asynccontextmanager

from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware

import data_loader
from routers import overview, movies, genres, ratings, analytics, hadoop

# ──────────────────────────────────────────────
# Logging configuration
# ──────────────────────────────────────────────
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s │ %(name)-30s │ %(levelname)-7s │ %(message)s",
    datefmt="%H:%M:%S",
)
logger = logging.getLogger("cinemetrics.main")


# ──────────────────────────────────────────────
# Lifespan: load data on startup
# ──────────────────────────────────────────────
@asynccontextmanager
async def lifespan(app: FastAPI):
    """
    Application lifespan handler.

    On startup: loads and caches all processed data from CSV/TSV files
    into memory so that API endpoints can respond instantly.

    On shutdown: performs any necessary cleanup (currently none needed).
    """
    logger.info("🚀 CineMetrics API starting up...")
    data_loader.init_data()
    logger.info("✅ Data loaded — API is ready to serve requests")
    yield
    logger.info("🛑 CineMetrics API shutting down...")


# ──────────────────────────────────────────────
# FastAPI app instance
# ──────────────────────────────────────────────
app = FastAPI(
    title="CineMetrics API",
    version="1.0.0",
    description=(
        "CineMetrics Analytics API — serves movie rating analytics computed "
        "by Hadoop MapReduce jobs on the MovieLens dataset. Provides endpoints "
        "for dashboard overview, movie browsing, genre analysis, rating "
        "distributions, trend analysis, and hidden gem discovery."
    ),
    lifespan=lifespan,
)

# ──────────────────────────────────────────────
# CORS middleware (allow all origins for development)
# ──────────────────────────────────────────────
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],           # Allow all origins during development
    allow_credentials=True,
    allow_methods=["*"],           # Allow all HTTP methods
    allow_headers=["*"],           # Allow all headers
)

# ──────────────────────────────────────────────
# Register routers
# ──────────────────────────────────────────────
app.include_router(overview.router)
app.include_router(movies.router)
app.include_router(genres.router)
app.include_router(ratings.router)
app.include_router(analytics.router)
app.include_router(hadoop.router)


@app.get("/", tags=["Health"])
async def root():
    """Health check endpoint — confirms the API is running."""
    return {
        "service": "CineMetrics API",
        "version": "1.0.0",
        "status": "running",
        "docs": "/docs",
    }
